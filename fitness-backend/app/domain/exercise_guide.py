def _media_links(slug, name):
    """참고 영상(유튜브)과 참고 자료(나무위키).

    영상은 검색으로 실제 존재를 확인한 것만 넣는다. 영상이 비공개로 바뀌거나
    삭제될 수 있으므로 검색 링크를 함께 둬서 막다른 길이 되지 않게 한다.
    """
    links = []
    video = VIDEOS.get(slug)

    if video:
        video_id, title = video
        links.append({
            "kind": "video",
            "label": title,
            "note": "유튜브에서 열립니다.",
            "url": f"https://www.youtube.com/watch?v={video_id}",
            "thumbnail": f"https://i.ytimg.com/vi/{video_id}/hqdefault.jpg",
        })

    links.append({
        "kind": "search",
        "label": "다른 영상 더 보기",
        "note": "유튜브 검색 결과로 이동합니다.",
        "url": f"https://www.youtube.com/results?search_query={quote(name + ' 자세')}",
        "thumbnail": None,
    })

    links.append({
        "kind": "wiki",
        "label": "나무위키에서 찾기",
        "note": "운동 설명과 배경 지식을 볼 수 있습니다.",
        "url": f"https://namu.wiki/Search?q={quote(name)}",
        "thumbnail": None,
    })

    return links


def guide_for(slug, name):
    guide = GUIDES.get(slug, FALLBACK)
    return {
        "steps": guide["steps"],
        "cues": guide["cues"],
        "mistake": guide["mistake"],
        "english": guide["en"],
        "media": _media_links(slug, name),
        "hasGuide": slug in GUIDES,
    }
